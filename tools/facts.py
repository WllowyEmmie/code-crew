"""Facts about the repo that the harness can measure, so no model has to guess them.

Written to memory as team/repo-facts.md at the start of every session, from the fresh clone
of the base branch. Agents can read it but not write it. This replaces model-written notes
about layout, test commands and line endings, which went stale or were simply wrong.
"""
from collections import Counter
from pathlib import Path, PurePosixPath

from .files import is_test_path
from .git import LANGUAGE_OF

MAX_FILES_LISTED = 150


def build_repo_facts(sb) -> str:
    repo = Path(sb.workdir)
    files = sb.run("git ls-files", timeout=30)["stdout"].split("\n")
    files = [f for f in files if f]
    tests = [f for f in files if is_test_path(f)]

    endings = Counter()
    for f in files:
        try:
            data = (repo / f).read_bytes()
        except OSError:
            continue
        if b"\0" in data[:4096]:
            continue  # binary
        endings["CRLF" if b"\r\n" in data else "LF"] += 1

    langs = ", ".join(p.name for p in sb.profiles) or "none detected"
    test_cmds = ", ".join(cmd for _, cmd in sb.test_commands()) or "none (no tests found)"
    where_lines = []
    for p in sb.profiles:  # per language, so one language's layout is never applied to another
        mine = [f for f in tests if p.name in LANGUAGE_OF.get(PurePosixPath(f).suffix, set())]
        dirs = sorted({str(PurePosixPath(f).parent) for f in mine})
        found = ", ".join("repo root" if d == "." else f"{d}/" for d in dirs) or "none yet"
        line = f"  - {p.name}: existing tests: {found}."
        if p.tests_go:
            line += f" Standard layout: {p.tests_go}."
        where_lines.append(line)
    where = "\n".join(where_lines) or "  - no languages detected"
    listed = files[:MAX_FILES_LISTED]
    more = f"\n- ... and {len(files) - len(listed)} more" if len(files) > len(listed) else ""

    return f"""---
name: repo-facts
description: Generated by the harness from {sb.start_branch} at the start of each session (read-only, always current)
---
- Languages: {langs}
- Test commands (git_commit runs them): {test_cmds}
- Where tests go, per language (follow the repo's existing tests; with none yet, use the standard layout):
{where}
- Line endings: {dict(endings) or 'no text files'} (edit_file keeps each file's existing style)
- Tracked files on {sb.start_branch} ({len(files)}):
""" + "\n".join(f"  - {f}" for f in listed) + more + "\n"
