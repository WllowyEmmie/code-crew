"""Agent-facing memory tools over MemoryStore.

Reading is progressive (the talk's "frontmatter + grep, not the whole store"):
memory_list shows only each file's description, memory_grep searches, memory_read opens one file.
Permissioning lives here: org/ is read-only, team/repo-facts.md belongs to the harness, and
only agents given can_delete (dreaming) may delete files.
"""
from langchain_core.tools import tool

from .memory_store import NEW, SHA_LEN, MemoryStore, WriteRefused

MAX_READ_CHARS = 20000
RESERVED = {"team/repo-facts.md"}  # written by the harness only


def make_memory_tools(store: MemoryStore, author: str, session: str,
                      can_write: bool = True, can_delete: bool = False, on_read=None,
                      write_check=None):
    """Tools for one agent. Every write is attributed to `author` in `session`.
    on_read() is called after each successful read/grep/list (used by the harness's read gate).
    write_check(path, content) -> error or None lets the harness verify content before saving."""

    def writable(path: str) -> str | None:
        if path.startswith("org/"):
            return "org/ is read-only (shared org knowledge). Write to team/ instead."
        if path in RESERVED:
            return f"{path} is generated by the harness and can't be edited."
        return None

    @tool
    def memory_list() -> str:
        """List every memory file with its one-line description (frontmatter only, not contents).
        Start here, then memory_grep or memory_read only what's relevant to your task."""
        if on_read:
            on_read("list")
        return "\n".join(f"{p} - {d}" for p, d in store.files()) or "(memory is empty)"

    @tool
    def memory_grep(pattern: str) -> str:
        """Search all memory files for a regex `pattern` (case-insensitive). Returns path:line:text."""
        try:
            hits = store.grep(pattern)
        except Exception as e:
            return f"error: {e}"
        if on_read:
            on_read("grep")
        return "\n".join(hits[:100]) or "(no matches)"

    @tool
    def memory_read(path: str) -> str:
        """Read one memory file, e.g. team/lessons.md. The first line shows its sha256,
        which you pass as if_sha256 if you then write or delete it."""
        try:
            text, digest = store.read(path)
        except FileNotFoundError:
            return f"error: {path} doesn't exist"
        except Exception as e:
            return f"error: {e}"
        if on_read:
            on_read("read")
        return f"[sha256: {digest[:SHA_LEN]}]\n{text[:MAX_READ_CHARS]}"

    @tool
    def memory_write(path: str, content: str, if_sha256: str, reason: str) -> str:
        """Create or replace a team/ memory file. Record what YOU judge future sessions need.
        - content: the WHOLE file: frontmatter (name, description) then one fact per line.
        - if_sha256: the sha256 memory_read showed you, or "new" to create a file.
          If the file changed since you read it, the write is refused: read again and merge.
        - reason: why this is worth keeping (e.g. "reviewer flagged this in round 2").
        Example content:
        ---
        name: lessons
        description: Mistakes made in earlier sessions and how to avoid them
        ---
        - Contractions like "it's" count as one word (reviewer feedback)
        """
        err = writable(path) or (write_check(path, content) if write_check else None)
        if err:
            return f"error: {err}"
        try:
            v = store.write(path, content, if_sha256, author, session, reason)
        except (WriteRefused, ValueError) as e:
            return f"error: {e}"
        return f"saved {path} as version {v}"

    @tool
    def memory_delete(path: str, if_sha256: str, reason: str) -> str:
        """Delete a team/ memory file (e.g. after merging it into another). Needs the sha256 from
        memory_read. The old content stays in version history and can be restored."""
        err = writable(path)
        if err:
            return f"error: {err}"
        try:
            v = store.delete(path, if_sha256, author, session, reason)
        except (WriteRefused, ValueError) as e:
            return f"error: {e}"
        return f"deleted {path} (version {v} records the deletion)"

    @tool
    def memory_history(path: str) -> str:
        """Show every version of a memory file: who wrote it, in which session, when, and why."""
        rows = store.history(path)
        if not rows:
            return "(no history yet)"
        return "\n".join(
            f"v{r['version']} {'DELETED' if r['deleted'] else r['sha256']} by {r['author']} "
            f"({r['session']}, {r['time']}): {r['note']}" for r in rows)

    tools = [memory_list, memory_grep, memory_read, memory_history]
    if can_write:
        tools.append(memory_write)
    if can_delete:
        tools.append(memory_delete)
    return tools
