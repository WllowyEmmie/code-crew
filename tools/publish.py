"""Publishing an approved session: push the crew's branch and open a pull request.

Runs in the harness, on your machine, after the reviewer approves. The agents never push and
never touch main: they work offline in the sandbox, and a human decides whether to merge.
- Push uses your normal git login (Git Credential Manager), from the session's repo copy.
- A pull request is opened if GITHUB_TOKEN is set (fine-grained token on this repo with
  "Pull requests: Read and write" and "Contents: Read-only"); otherwise you get a link.
- Set PUBLISH=false in .env to keep everything local.
"""
import json
import os
import re
import subprocess
import urllib.error
import urllib.request

GITHUB = re.compile(r"github\.com[:/]([^/]+)/([^/]+?)(?:\.git)?/?$")


def _git(workdir: str, *args) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", workdir, *args], capture_output=True, text=True)


def _remote_has(workdir: str, branch: str) -> bool:
    r = _git(workdir, "ls-remote", "--heads", "origin", branch)
    return bool(r.stdout.strip())


def pr_title(sb, state: dict) -> str:
    """The builder's first commit subject ("[code-crew] Add scheduler crate with free_slots"),
    which is already a short summary of the change. The full request goes in the PR body."""
    subjects = _git(sb.workdir, "log", "--reverse", "--format=%s",
                    f"{sb.start_commit}..HEAD").stdout.split("\n")
    first = next((x.strip() for x in subjects if x.strip()), "")
    if not first:
        first = "[code-crew] " + " ".join(state.get("request", "").split())[:70]
    return first if len(first) <= 90 else first[:87].rstrip() + "..."


def pr_body(state: dict, session: str) -> str:
    return "\n".join([
        "> Generated by **code-crew** (builder -> test-writer -> reviewer). Review before merging.",
        "",
        f"**Request:** {state.get('request')}",
        f"**Outcome:** {state.get('status')} after {state.get('round', 1)} round(s), session `{session}`",
        "",
        "### Builder", state.get("builder_summary") or "-",
        "", "### Tests", state.get("test_summary") or "-",
        "", "### Review", state.get("review_summary") or "-",
        "", "Every commit carries `Generated-by: code-crew` and the agent that made it.",
    ])


def _api(method: str, path: str, token: str, data: dict | None = None):
    req = urllib.request.Request(
        f"https://api.github.com{path}", method=method,
        data=json.dumps(data).encode() if data is not None else None,
        headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
                 "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "code-crew"},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def open_pull_request(owner: str, repo: str, head: str, base: str, title: str, body: str, token: str) -> str:
    pr = _api("POST", f"/repos/{owner}/{repo}/pulls", token,
              {"title": title, "head": head, "base": base, "body": body})
    return pr["html_url"]


def find_open_pull_request(owner: str, repo: str, branch: str, token: str) -> dict | None:
    prs = _api("GET", f"/repos/{owner}/{repo}/pulls?state=open&head={owner}:{branch}", token)
    return prs[0] if prs else None


def publish(sb, state: dict, repo_url: str) -> dict:
    if os.getenv("PUBLISH", "true").lower() in ("false", "0", "no"):
        print("[publish] PUBLISH=false: branch kept local")
        return {"published": False}
    workdir = sb.workdir
    branch = _git(workdir, "branch", "--show-current").stdout.strip()
    if not branch.startswith("code-crew/"):
        print(f"[publish] not pushing: on {branch!r}, expected a code-crew/ branch")
        return {"published": False}
    if state.get("status") != "approved":
        return _push_draft(sb, state, branch)
    remote_branch = branch
    continuing = getattr(sb, "continuing", None)
    # A new task never overwrites an existing remote branch (e.g. an earlier run of the same task).
    # Continuing a branch pushes new commits on top of it (a normal push, never a force push).
    if not continuing and _remote_has(workdir, remote_branch):
        remote_branch = f"{branch}-{sb.session_id[-6:]}"
    r = _git(workdir, "push", "origin", f"HEAD:refs/heads/{remote_branch}")
    if r.returncode != 0:
        print(f"[publish] push failed:\n{r.stderr.strip()}")
        return {"published": False, "error": r.stderr.strip()}
    print(f"[publish] pushed {remote_branch}")

    m = GITHUB.search(repo_url)
    if not m:
        return {"published": True, "branch": remote_branch}
    owner, repo = m.group(1), m.group(2)
    compare = f"https://github.com/{owner}/{repo}/compare/{sb.base_branch}...{remote_branch}?expand=1"
    token = os.getenv("GITHUB_TOKEN")
    if continuing:
        return _update_existing(owner, repo, remote_branch, state, sb, token, compare)
    if not token:
        print(f"[publish] open a pull request here: {compare}")
        return {"published": True, "branch": remote_branch, "pr_url": compare}
    title = pr_title(sb, state)
    try:
        url = open_pull_request(owner, repo, remote_branch, sb.base_branch, title,
                                pr_body(state, sb.session_id), token)
        print(f"[publish] pull request opened: {url}")
        return {"published": True, "branch": remote_branch, "pr_url": url}
    except urllib.error.HTTPError as e:
        detail = e.read().decode()[:200]
        hint = ""
        if "not all refs are readable" in detail or e.code in (401, 403):
            hint = (" The token can't read this repo's branches: give it Repository permissions "
                    "'Contents: Read-only' and 'Pull requests: Read and write' for this repo.")
        print(f"[publish] couldn't open the PR ({e.code}: {detail}).{hint} Open it here: {compare}")
        return {"published": True, "branch": remote_branch, "pr_url": compare}


def _push_draft(sb, state: dict, branch: str) -> dict:
    """An unapproved session that made commits: push the branch so the work isn't stuck in a temp
    folder and `--branch` can continue it, but open no pull request (nothing is offered for merge).
    A branch that already has a pull request is left alone, so a failed retry never puts
    unreviewed commits into a PR."""
    status = state.get("status")
    workdir = sb.workdir
    made = _git(workdir, "rev-list", "--count", f"{sb.start_commit}..HEAD").stdout.strip()
    if made in ("", "0"):
        print(f"[publish] not pushing: status is {status!r} and no commits were made")
        return {"published": False}
    if getattr(sb, "continuing", None):
        print(f"[publish] not pushing: status is {status!r}; {branch} on GitHub may have a pull "
              f"request, so the new commits stay local in {workdir}")
        return {"published": False}
    remote_branch = branch
    if _remote_has(workdir, remote_branch):
        remote_branch = f"{branch}-{sb.session_id[-6:]}"
    r = _git(workdir, "push", "origin", f"HEAD:refs/heads/{remote_branch}")
    if r.returncode != 0:
        print(f"[publish] draft push failed:\n{r.stderr.strip()}")
        return {"published": False, "error": r.stderr.strip()}
    print(f"[publish] status is {status!r}: pushed {remote_branch} as an unapproved draft (no pull request). "
          f"Continue it with: python run_crew.py --branch {remote_branch} \"...\"")
    return {"published": False, "draft": True, "branch": remote_branch}


def _update_existing(owner, repo, branch, state, sb, token, compare) -> dict:
    """The push already updated the branch, so its open pull request now shows the new commits.
    Leave a comment there saying what this round changed, rather than opening a second PR."""
    if not token:
        print(f"[publish] the pull request for {branch} now has the new commits: "
              f"https://github.com/{owner}/{repo}/pulls?q=is%3Apr+head%3A{branch}")
        return {"published": True, "branch": branch}
    try:
        pr = find_open_pull_request(owner, repo, branch, token)
        if pr is None:  # e.g. it was closed: open a fresh one for the branch
            url = open_pull_request(owner, repo, branch, sb.base_branch,
                                    pr_title(sb, state),
                                    pr_body(state, sb.session_id), token)
            print(f"[publish] no open pull request for {branch}; opened {url}")
            return {"published": True, "branch": branch, "pr_url": url}
        comment = ("**code-crew pushed an update to this pull request.**\n\n" + pr_body(state, sb.session_id))
        _api("POST", f"/repos/{owner}/{repo}/issues/{pr['number']}/comments", token, {"body": comment})
        print(f"[publish] updated pull request #{pr['number']} and commented: {pr['html_url']}")
        return {"published": True, "branch": branch, "pr_url": pr["html_url"]}
    except urllib.error.HTTPError as e:
        print(f"[publish] pushed, but couldn't comment on the PR ({e.code}). The new commits are on {branch}.")
        return {"published": True, "branch": branch, "pr_url": compare}
